window.GRY_MODULES.pisownia = {
    id: "pisownia",
    nazwa: "Mistrz Ortografii",
    ikona: "✏️",
    opis: "Uzupełnij brakującą literę w słowie",
    edytowalna: true,

    dane: DANE_DOMYSLNE_PISOWNIA.slice(),
    _domyslneDane: DANE_DOMYSLNE_PISOWNIA,

    _aktualne: null,
    _lock: false,

    init(kontener) {
        this._render(kontener);
        this._losuj();
    },

    _render(kontener) {
        kontener.innerHTML = `
            <div class="config-box" style="background-color:var(--bg-card);padding:15px;border-radius:16px;margin-bottom:20px;">
                <label for="pisownia-tryb" style="font-size:0.9rem;color:var(--text-secondary);display:block;margin-bottom:8px;">Wybierz zakres ćwiczeń:</label>
                <select id="pisownia-tryb" style="width:100%;padding:12px;border-radius:10px;background-color:var(--bg-input);color:var(--text-primary);border:2px solid var(--accent-pisownia);font-size:1rem;font-weight:bold;outline:none;">
                    <option value="Wszystkie">Wszystkie słowa</option>
                    <option value="u/ó">Zakres: u / ó</option>
                    <option value="rz/ż">Zakres: rz / ż (i wyjątki sz)</option>
                    <option value="h/ch">Zakres: h / ch</option>
                </select>
            </div>
            <div class="pole-glowne" id="pisownia-ekran" style="--accent-gry: var(--accent-pisownia); position:relative; font-size:2.2rem;">
                <div id="pisownia-kategoria" style="position:absolute;top:10px;right:15px;font-size:0.75rem;color:var(--text-muted);background:var(--bg-input);padding:4px 10px;border-radius:20px;">Kategoria: -</div>
                <div id="pisownia-ikona" style="font-size:2.2rem;margin-bottom:10px;min-height:50px;display:flex;align-items:center;justify-content:center;">❓</div>
                <div id="pisownia-slowo">___</div>
            </div>
            <div class="siatka-opcje" id="pisownia-klawiatura" style="grid-template-columns: repeat(auto-fit, minmax(70px, 1fr));"></div>
            <div class="feedback-box" id="pisownia-feedback"></div>
        `;
        document.getElementById("pisownia-tryb").onchange = () => this._losuj();
    },

    _losuj() {
        const tryb = document.getElementById("pisownia-tryb").value;
        const feedback = document.getElementById("pisownia-feedback");
        feedback.textContent = "";
        feedback.className = "feedback-box";

        const pasujace = this.dane.filter((w) => {
            if (tryb === "Wszystkie") return true;
            if (tryb === "rz/ż") return w.kat === "rz/ż" || w.kat === "wyjątki";
            return w.kat === tryb;
        });
        if (pasujace.length === 0) return;

        const wylosowane = pasujace[Math.floor(Math.random() * pasujace.length)];
        this._aktualne = wylosowane;

        const poz = wylosowane.pelne.toLowerCase().indexOf(wylosowane.poprawna.toLowerCase());
        const tekst =
            poz >= 0
                ? wylosowane.pelne.substring(0, poz) + " ___ " + wylosowane.pelne.substring(poz + wylosowane.poprawna.length)
                : " ___ " + wylosowane.pelne;

        document.getElementById("pisownia-ikona").innerHTML = window.GRY_UTILS.ikonaHtml(wylosowane.ikona || "💡");
        document.getElementById("pisownia-kategoria").textContent = `Kategoria: ${wylosowane.kat}`;
        const slowoEl = document.getElementById("pisownia-slowo");
        slowoEl.textContent = tekst;
        slowoEl.className = "slowo-neutralny";

        this._generujKlawiature(tryb, wylosowane.kat);
    },

    _generujKlawiature(tryb, katAktualnego) {
        const klawiatura = document.getElementById("pisownia-klawiatura");
        klawiatura.innerHTML = "";

        let litery = ["u", "ó", "rz", "ż", "sz", "h", "ch"];
        const kat = tryb === "Wszystkie" ? katAktualnego : tryb;
        if (kat === "u/ó") litery = ["u", "ó"];
        else if (kat === "rz/ż" || kat === "wyjątki") litery = ["rz", "ż", "sz"];
        else if (kat === "h/ch") litery = ["h", "ch"];

        litery.forEach((litera) => {
            const btn = document.createElement("button");
            btn.className = "btn-opcja";
            btn.textContent = litera;
            btn.onclick = () => this._sprawdz(litera);
            klawiatura.appendChild(btn);
        });
    },

    _sprawdz(odpowiedz) {
        if (this._lock || !this._aktualne) return;
        const slowoEl = document.getElementById("pisownia-slowo");
        const { pelne, poprawna } = this._aktualne;

        if (odpowiedz.toLowerCase() === poprawna.toLowerCase()) {
            slowoEl.textContent = pelne;
            slowoEl.className = "slowo-sukces";
            this._lock = true;
            setTimeout(() => {
                this._lock = false;
                this._losuj();
            }, 1200);
        } else {
            const poz = pelne.toLowerCase().indexOf(poprawna.toLowerCase());
            if (poz >= 0) {
                slowoEl.textContent = pelne.substring(0, poz) + odpowiedz.toUpperCase() + pelne.substring(poz + poprawna.length);
            }
            slowoEl.className = "slowo-blad";
        }
    },
};
